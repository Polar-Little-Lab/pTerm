import test from 'node:test';
import assert from 'node:assert/strict';
import React,{act} from 'react';
import {createRoot} from 'react-dom/client';
import {JSDOM} from 'jsdom';
import {InlineSuggestions} from '../src/InlineSuggestions';
import type {Session} from '../src/types';

test('typing, Tab, Escape, stale input and workspace lock use the real component',async()=>{
 const dom=new JSDOM('<div id="mount"></div><div id="surface"><textarea></textarea></div>');
 Object.assign(globalThis,{window:dom.window,document:dom.window.document,IS_REACT_ACT_ENVIRONMENT:true});
 const events:Record<string,Set<Function>>={data:new Set(),parsed:new Set(),scroll:new Set()};
 const subscribe=(name:string)=>(fn:Function)=>{events[name].add(fn);return {dispose:()=>events[name].delete(fn)};};
 let before='user@mac ~ % df',after='',kind='normal';
 const inserted:string[]=[];
 const buffer={get type(){return kind;},viewportY:0,baseY:0,cursorY:0,cursorX:before.length,getLine:()=>({isWrapped:false,translateToString:(_trim:boolean,start:number,end?:number)=>end!==undefined?before:after})};
 const terminal={buffer:{active:buffer},rows:24,cols:80,onData:subscribe('data'),onWriteParsed:subscribe('parsed'),onScroll:subscribe('scroll'),input:(s:string)=>inserted.push(s),focus:()=>{}};
 const session={terminal,status:'connected',closed:false} as unknown as Session;
 const surface={current:document.getElementById('surface') as HTMLDivElement};
 const root=createRoot(document.getElementById('mount')!);
 const snippets=[{id:'one',name:'Disk',command:'df -h'}];
 const render=(unlocked=true,enabled=true)=>act(()=>root.render(<InlineSuggestions session={session} snippets={unlocked?snippets:undefined} enabled={enabled} surface={surface}/>));
 const emit=(name:string,value?:string)=>act(()=>{for(const fn of events[name])fn(value);});
 const type=()=>{emit('data','f');emit('parsed');};
 const key=(name:string)=>{let event:KeyboardEvent;act(()=>{event=new dom.window.KeyboardEvent('keydown',{key:name,bubbles:true,cancelable:true});surface.current.querySelector('textarea')!.dispatchEvent(event);});return event!;};
 await render();
 emit('parsed');assert.equal(document.querySelector('.inline-suggestions'),null,'output alone cannot open suggestions');
 type();assert.match(document.querySelector('.inline-suggestions')!.textContent!,/df -h/);
 assert.equal(key('Tab').defaultPrevented,true);assert.deepEqual(inserted,[' -h']);
 assert.equal(inserted.some(s=>s.includes('\n')),false);
 type();key('Escape');emit('parsed');assert.equal(document.querySelector('.inline-suggestions'),null);
 type();before='Password: df';key('Tab');assert.equal(inserted.length,1,'stale line cannot insert');
 before='user@mac ~ % df';type();await render(false);assert.equal(document.querySelector('.inline-suggestions'),null);assert.equal(events.data.size,0);
 await render();kind='alternate';type();assert.equal(document.querySelector('.inline-suggestions'),null);
 kind='normal';after=' -i';type();assert.equal(document.querySelector('.inline-suggestions'),null);
 after='';type();key('Enter');emit('parsed');assert.equal(document.querySelector('.inline-suggestions'),null);
 type();await render(true,false);assert.equal(document.querySelector('.inline-suggestions'),null);
 await act(()=>root.unmount());assert.equal(events.parsed.size,0);
 dom.window.close();
});
